#!/usr/bin/env python3
# scripts/build-m3-tokens.py
"""
Build M3 Expressive design tokens into CSS variables and Tailwind configuration.
Supports DTCG format (extracting $value) and handles 'sys' wrapper.
"""
import json
import os
import sys

# Define I/O paths
TOKEN_SOURCE_FILE = 'frontend/src/design/tokens/tokens.json'
CSS_OUTPUT_FILE = 'frontend/src/design/styles/design-tokens.css'
TAILWIND_CONFIG_PATCH = 'frontend/tailwind-m3-patch.js'

def load_tokens():
    """Loads the M3 Expressive JSON tokens."""
    print(f"Loading tokens from {TOKEN_SOURCE_FILE}...")
    if not os.path.exists(TOKEN_SOURCE_FILE):
        print(f"Error: Token source file not found at {TOKEN_SOURCE_FILE}")
        return None
    with open(TOKEN_SOURCE_FILE, 'r') as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            print(f"Error: Invalid JSON in token file. {e}")
            sys.exit(1)

def resolve_values(node):
    """Recursively extracts $value from DTCG nodes."""
    if isinstance(node, dict):
        if '$value' in node:
            return resolve_values(node['$value'])
        # Filter out metadata keys starting with $ (like $description, $type) unless it's the value itself
        return {k: resolve_values(v) for k, v in node.items() if not k.startswith('$')}
    elif isinstance(node, list):
        return [resolve_values(x) for x in node]
    return node

def flatten_dict(d, parent_key='', sep='-'):
    """Flattens a dictionary into CSS variable friendly keys."""
    items = []
    for k, v in d.items():
        new_key = f"{parent_key}{sep}{k}" if parent_key else k
        if isinstance(v, dict):
            items.extend(flatten_dict(v, new_key, sep=sep).items())
        else:
            items.append((new_key, v))
    return dict(items)

def generate_css_variables(tokens):
    """Generates CSS variables from resolved tokens."""
    print(f"Generating CSS variables at {CSS_OUTPUT_FILE}...")
    os.makedirs(os.path.dirname(CSS_OUTPUT_FILE), exist_ok=True)

    content = [
        "/* Kerala Rage Design Tokens */\n",
        "/* Auto-generated by scripts/build-m3-tokens.py */\n",
        "/* Do not edit this file directly */\n\n",
        ":root {\n"
    ]

    flat_tokens = flatten_dict(tokens)
    
    for key, value in flat_tokens.items():
        # Skip array values for CSS variables (unless we join them, but usually individual tokens are preferred)
        if isinstance(value, list):
            # Optionally expand arrays: color-red-0, color-red-1...
            for i, item in enumerate(value):
                var_name = f"--sys-{key}-{i}"
                content.append(f"  {var_name}: {item};\n")
        else:
            var_name = f"--sys-{key}"
            content.append(f"  {var_name}: {value};\n")

    content.append("}\n")
    
    # Add utility classes for common references if structure allows
    # (Optional: Add specific utilities based on known keys like 'color-charcoalBackground-base')
    
    with open(CSS_OUTPUT_FILE, 'w') as f:
        f.writelines(content)
        
    print(f"✅ Generated {len(content)} lines of CSS variables")
    return True

def generate_tailwind_patch(tokens):
    """Generates Tailwind config patch."""
    print(f"Generating Tailwind patch at {TAILWIND_CONFIG_PATCH}...")
    os.makedirs(os.path.dirname(TAILWIND_CONFIG_PATCH), exist_ok=True)

    # Prepare Tailwind Theme Object
    # We map semantic token groups to Tailwind theme sections
    
    tw_theme = {
        'colors': {},
        'fontFamily': {},
        'fontSize': {},
        'borderRadius': {},
        'boxShadow': {},
        'transitionTimingFunction': {},
        'transitionDuration': {}
    }


    # Map Colors
    if 'color' in tokens:
        for name, value in tokens['color'].items():
            if isinstance(value, dict):
                # Handle base + steps
                color_def = {}
                if 'base' in value:
                     color_def['DEFAULT'] = value['base'] # var(--md-sys-color-name-base)
                     # Instead of hardcoding value, use CSS var reference? 
                     # For seamless handover, let's use the CSS var for live updates.
                     color_def['DEFAULT'] = f"var(--sys-color-{name}-base)"
                
                if 'steps' in value and isinstance(value['steps'], list):
                    for i, step in enumerate(value['steps']):
                        color_def[str(i)] = f"var(--sys-color-{name}-steps-{i})"

                tw_theme['colors'][name] = color_def
            else:
                tw_theme['colors'][name] = f"var(--sys-color-{name})"

    # Map Typography
    if 'type' in tokens:
        # Font Families
        if 'fontFamilies' in tokens['type']:
            for name, val in tokens['type']['fontFamilies'].items():
                tw_theme['fontFamily'][name] = [f"var(--sys-type-fontFamilies-{name})"]
        
        # Scale (Font Sizes)
        if 'scale' in tokens['type']:
             for name, val in tokens['type']['scale'].items():
                  tw_theme['fontSize'][name] = f"var(--sys-type-scale-{name})"

    # Map Shapes
    if 'shape' in tokens:
        for name, val in tokens['shape'].items():
            tw_theme['borderRadius'][name] = f"var(--sys-shape-{name})"

    # Map Shadows
    if 'shadow' in tokens:
         for name, val in tokens['shadow'].items():
              tw_theme['boxShadow'][name] = f"var(--sys-shadow-{name})"

    # Map Motion
    if 'motion' in tokens:
        # Easing
        if 'm3Expressive' in tokens['motion']:
             # Join array if it's a list [0.34, 1.56...]
             val = tokens['motion']['m3Expressive']
             if isinstance(val, list):
                 val_str = f"cubic-bezier({', '.join(map(str, val))})"
                 tw_theme['transitionTimingFunction']['expressive'] = val_str # Hard to use var for bezier in TW sometimes
             else:
                  tw_theme['transitionTimingFunction']['expressive'] = f"var(--sys-motion-m3Expressive)"

        # Patterns (Duration?)
        if 'patterns' in tokens['motion']:
             for name, pattern in tokens['motion']['patterns'].items():
                  if isinstance(pattern, dict) and 'duration' in pattern:
                       tw_theme['transitionDuration'][name] = f"var(--sys-motion-patterns-{name}-duration)"


    patch_content = f"""// Kerala Rage Tailwind Patch
// Auto-generated by scripts/build-m3-tokens.py
module.exports = {{
  theme: {{
    extend: {json.dumps(tw_theme, indent=6)}
  }}
}};
"""
    with open(TAILWIND_CONFIG_PATCH, 'w') as f:
        f.write(patch_content)
    
    print("✅ Tailwind config patch generated")
    return True

def main():
    print("=" * 60)
    print("Kerala Rage Token Builder (DTCG)")
    print("=" * 60)

    raw_tokens = load_tokens()
    if not raw_tokens:
        sys.exit(1)

    # Unwrap 'sys' if present
    root = raw_tokens
    if 'sys' in root:
        print("ℹ️  Unwrapping 'sys' token group.")
        root = root['sys']
    
    # Resolve $value references
    print("RESOLVING DTCG values...")
    tokens = resolve_values(root)
    
    # Filter out top-level compliance or documentation keys
    if isinstance(tokens, dict):
        tokens = {k: v for k, v in tokens.items() if k not in ['compliance', 'documentation']}

    
    if not tokens:
        print("❌ No tokens found after resolution")
        sys.exit(1)

    # Build outputs
    success_css = generate_css_variables(tokens)
    success_tw = generate_tailwind_patch(tokens)

    if success_css and success_tw:
        print("\n✨ Build complete!")
        print(f"Files:\n  - {CSS_OUTPUT_FILE}\n  - {TAILWIND_CONFIG_PATCH}")
    else:
        sys.exit(1)

if __name__ == "__main__":
    main()
