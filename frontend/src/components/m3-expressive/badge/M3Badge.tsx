/**
 * M3 Expressive Badge Component
 * Implements Material Design 3 Badge for CareerCopilot
 *
 * Uses CSS variables from m3-design-tokens.css:
 * - Color: --md-sys-color-*
 * - Shape: --md-sys-shape-corner-*
 * - Typography: --md-sys-typescale-*
 * - Spacing: --md-sys-spacing-*
 * - Motion: --md-sys-motion-*
 * - Elevation: --md-sys-elevation-*
 *
 * NOTE: CSS styles (M3Badge.css) must be imported in the application root
 * or in pages that use this component.
 */

import React from 'react';

export interface M3BadgeProps
  extends React.HTMLAttributes<HTMLDivElement> {
  /**
   * [Add your variant prop]
   * @default 'default'
   */
  // variant?: 'default' | 'variant2';

  /**
   * [Add your color prop]
   * @default 'primary'
   */
  // color?: 'primary' | 'secondary' | 'tertiary' | 'error';

  /**
   * Component content
   */
  children?: React.ReactNode;
}

/**
 * M3 Expressive Badge component using design tokens.
 *
 * Example usage:
 * ```tsx
 * <M3Badge>Content</M3Badge>
 * ```
 */
export const M3Badge = React.forwardRef<
  HTMLDivElement,
  M3BadgeProps
>(
  (
    {
      // variant = 'default',
      // color = 'primary',
      className = '',
      children,
      ...props
    },
    ref
  ) => {
    const classNames = [
      'm3-badge',
      // `m3-badge--${variant}`,
      // `m3-badge--${color}`,
      className,
    ]
      .filter(Boolean)
      .join(' ');

    return (
      <div
        ref={ref}
        className={classNames}
        {...props}
      >
        {children}
      </div>
    );
  }
);

M3Badge.displayName = 'M3Badge';

export default M3Badge;
